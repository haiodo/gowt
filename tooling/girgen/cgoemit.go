package main

import (
	"fmt"
	"strings"
)

// Opt-in cgo backend (linux && gowtcgo && cgo): next to every generated purego
// wrapper the generator emits a gen_funcs_<part>_cgo.go twin carrying one typed C
// wrapper per native. The wrapper takes the dlsym'd address as its first argument
// and calls through an exactly typed function pointer - no purego/libffi on this
// path. Lazy/optional semantics stay in Go: lz.get resolves the symbol at bind
// time, so a symbol missing from the loaded GTK still becomes the panicking stub
// instead of a C abort, and a missing GTK still yields zero functions during
// package init. Hand-written glue natives have no generated wrapper (empty name)
// and bind through purego in both backends.

type cgoNative struct {
	name   string // Go binding name, registry key
	csym   string // C symbol to dlsym (kept for lz.get's symbol check)
	params []string
	ret    string // "" for void
}

// cCType maps a raw Go parameter type to the C spelling used by the wrapper.
func cCType(raw string) string {
	switch raw {
	case "unsafe.Pointer":
		return "void*"
	case "uintptr":
		return "uintptr_t"
	case "int32":
		return "int32_t"
	case "int16":
		return "int16_t"
	case "int8":
		return "int8_t"
	case "float32":
		return "float"
	case "float64":
		return "double"
	}
	panic("girgen: cgo backend: no C type for raw Go type " + raw)
}

// cgoFileText renders one part's cgo twin file, or "" when the part has no natives.
func cgoFileText(natives []cgoNative) string {
	if len(natives) == 0 {
		return ""
	}
	var c, gob strings.Builder
	c.WriteString("#include <stdint.h>\n#include <stdio.h>\n#include <stdlib.h>\n#include <dlfcn.h>\n\n")
	needUnsafe := false
	for i := range natives {
		n := &natives[i]
		var ctypes, cparams, cargs []string
		cparams = append(cparams, "uintptr_t fn")
		for j, raw := range n.params {
			ct := cCType(raw)
			an := fmt.Sprintf("a%d", j)
			ctypes = append(ctypes, ct)
			cparams = append(cparams, ct+" "+an)
			if raw == "unsafe.Pointer" {
				cargs = append(cargs, an)
				needUnsafe = true
			} else {
				cargs = append(cargs, fmt.Sprintf("C.%s(%s)", ct, an))
			}
		}
		cret := "void"
		if n.ret != "" {
			cret = cCType(n.ret)
		}
		// The wrapper: cast the address to the exact signature and call it directly.
		csig := strings.Join(ctypes, ", ")
		if csig == "" {
			csig = "void"
		}
		call := fmt.Sprintf("((%s (*)(%s))fn)(%s)", cret, csig, cArgNames(len(n.params)))
		fmt.Fprintf(&c, "static %s gowt_%s(%s) {\n", cret, n.name, strings.Join(cparams, ", "))
		if n.ret == "" {
			c.WriteString("\t" + call + ";\n}\n\n")
		} else {
			c.WriteString("\treturn " + call + ";\n}\n\n")
		}
		// Go side: the constructor turning the dlsym'd address into the bound func.
		var gparams []string
		for j, raw := range n.params {
			gparams = append(gparams, fmt.Sprintf("a%d %s", j, raw))
		}
		gsig := strings.Join(gparams, ", ")
		gcall := fmt.Sprintf("C.gowt_%s(C.uintptr_t(addr)%s)", n.name, cGoArgs(cargs))
		fmt.Fprintf(&gob, "func cgoBind_%s(addr uintptr) func(%s) ", n.name, gsig)
		if n.ret != "" {
			gob.WriteString(n.ret + " ")
		}
		gob.WriteString("{\n\treturn func(" + gsig + ") ")
		if n.ret != "" {
			gob.WriteString(n.ret + " ")
		}
		gob.WriteString("{\n\t\t")
		if n.ret == "" {
			gob.WriteString(gcall + "\n")
		} else {
			gob.WriteString("return " + n.ret + "(" + gcall + ")\n")
		}
		gob.WriteString("\t}\n}\n\n")
	}
	var f strings.Builder
	f.WriteString("// Code generated by girgen from GIR files. DO NOT EDIT.\n")
	f.WriteString("//go:build linux && gowtcgo && cgo\n\n")
	f.WriteString("package gtk\n\n")
	f.WriteString("/*\n" + c.String() + "*/\n")
	f.WriteString("import \"C\"\n\n")
	if needUnsafe {
		f.WriteString("import \"unsafe\"\n\n")
	}
	f.WriteString(gob.String())
	// Package-level registration, not func init(): variable initializers run before
	// any init() regardless of file order, and glue/swt initialisers call natives.
	f.WriteString("var _ = func() int {\n")
	for _, n := range natives {
		fmt.Fprintf(&f, "\tcgoNativeRegistry[%q] = cgoBind_%s\n", n.name, n.name)
	}
	f.WriteString("\treturn 0\n}()\n")
	return f.String()
}

func cArgNames(n int) string {
	var b strings.Builder
	for i := 0; i < n; i++ {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "a%d", i)
	}
	return b.String()
}

func cGoArgs(args []string) string {
	if len(args) == 0 {
		return ""
	}
	return ", " + strings.Join(args, ", ")
}
