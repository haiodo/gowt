// girgen emits internal/gtk (purego bindings) from GIR files for exactly the names the SWT widget
// code uses; the call-site names are the interface spec (see README, "GIR-driven gtk binding").
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"
)

var base3 = []string{"Gtk-3.0", "Gdk-3.0", "GdkX11-3.0", "GObject-2.0", "GLib-2.0", "Gio-2.0", "Pango-1.0", "PangoCairo-1.0", "cairo-1.0", "Atk-1.0", "GdkPixbuf-2.0"}

// The GTK 4 index also needs the shared types (PangoWrapMode, cairo_content_t, ...) to type its parameters.
var base4 = []string{"Gtk-4.0", "Gdk-4.0", "GdkX11-4.0", "Gsk-4.0", "Graphene-1.0", "GObject-2.0", "GLib-2.0", "Gio-2.0", "Pango-1.0", "PangoCairo-1.0", "cairo-1.0", "Atk-1.0", "GdkPixbuf-2.0"}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "girgen:", err)
	os.Exit(1)
}

func loadIndex(dir string, names []string) *Index {
	ix := newIndex()
	for _, n := range names {
		r, err := loadRepo(dir, n)
		if err != nil {
			fatal(err)
		}
		ix.add(r, n)
	}
	return ix
}

const header = "// Code generated by girgen from GIR files. DO NOT EDIT.\n//go:build linux\n\npackage gtk\n\n"

func main() {
	girDir := flag.String("gir", "/usr/share/gir-1.0", "GIR directory")
	roots := flag.String("src", "swt,tests,cmd,examples", "comma-separated roots scanned for gtk.<Name> call sites")
	out := flag.String("out", "internal/gtk", "output directory")
	shapesPath := flag.String("shapes", "tooling/girgen/shapes.txt", "hand-written signature corrections")
	fitPath := flag.String("fit", "tooling/girgen/shapes_fit.txt", "corrections recorded from build errors")
	fitLog := flag.String("fit-log", "", "go build log to learn call-site parameter types from (updates -fit and exits)")
	report := flag.Bool("report", false, "print unresolved names and exit")
	layoutC := flag.String("layout-c", "", "write a C program that prints sizeof/offsetof of every emitted struct")
	layoutExp := flag.String("layout-expect", "", "write the computed struct table in the C program's output format")
	eplRoot := flag.String("epl", os.Getenv("SWT_REPO"), "SWT repository root; its EPL Java sources show how members are spelled (with -jstubs)")
	jstubs := flag.String("jstubs", "", "write Java declarations of the exported internal/gtk API into this directory (type information for j2go) and exit")
	flag.Parse()
	if *jstubs != "" {
		calls, err := callArity(strings.Split(*roots, ","))
		if err != nil {
			fatal(err)
		}
		shapes, _ := loadShapes(*shapesPath)
		fit, _ := loadShapes(*fitPath)
		shapes.merge(fit)
		csyms := map[string]string{}
		for n, e := range shapes.Func {
			csyms[n] = e.CSym
		}
		dirs := []string{filepath.Join(*eplRoot, "bundles/org.eclipse.swt"), filepath.Join(*eplRoot, "tests/org.eclipse.swt.tests/JUnit Tests"), filepath.Join(*eplRoot, "examples/org.eclipse.swt.examples/src")}
		spell, err := eplSpellings(dirs)
		if err != nil {
			fatal(err)
		}
		if err := writeJStubs(*out, *jstubs, calls, spell, csyms); err != nil {
			fatal(err)
		}
		return
	}
	names, called, err := usedNames(strings.Split(*roots, ","))
	if err != nil {
		fatal(err)
	}
	if *fitLog != "" {
		f := loadFit(*fitPath)
		n := f.runFit(*fitLog, ".")
		if err := f.save(*fitPath); err != nil {
			fatal(err)
		}
		for _, s := range f.notes {
			fmt.Println(s)
		}
		fmt.Fprintf(os.Stderr, "fit: %d entries changed\n", n)
		return
	}
	shapes, err := loadShapes(*fitPath)
	if err != nil {
		fatal(err)
	}
	manual, err := loadShapes(*shapesPath)
	if err != nil {
		fatal(err)
	}
	shapes.merge(manual)
	names = append(names, shapes.Need...)
	glue, err := glueNames(*out)
	if err != nil {
		fatal(err)
	}
	ix3, ix4 := loadIndex(*girDir, base3), loadIndex(*girDir, base4)
	hdr := "/usr/include/cairo/"
	addCairoProtos(ix3, []string{hdr + "cairo.h", hdr + "cairo-xlib.h", hdr + "cairo-pdf.h", hdr + "cairo-ps.h"})
	g := &gen{res: &Resolver{ix3: ix3, ix4: ix4, shapes: shapes, called: called}, shapes: shapes, structs: map[string]bool{}, layouts: map[string]*Layout{}, emitted: map[string]bool{}}
	counts := map[string]int{}
	for _, n := range names {
		if glue[n] {
			continue
		}
		s := g.res.resolve(n)
		g.syms = append(g.syms, s)
		counts[s.Kind]++
		if s.Kind == "type" {
			g.structs[s.Go], g.structs[s.TypeCT] = true, true
		}
		if s.Kind == "unresolved" && *report {
			fmt.Println(s.Go)
		}
	}
	fmt.Fprintln(os.Stderr, counts)
	if *report {
		return
	}
	funcs, consts, types := g.emitAll()
	files := map[string]string{
		"gen_funcs.go":       header + "import \"unsafe\"\n\n" + funcs,
		"gen_consts.go":      header + consts,
		"gen_layout_test.go": g.layoutTest(g.emitted),
		"gen_types.go":       header + "import \"unsafe\"\n\nvar _ unsafe.Pointer\n\n" + types,
	}
	for n, c := range files {
		src, err := format.Source([]byte(c))
		if err != nil {
			fatal(fmt.Errorf("%s: %w", n, err))
		}
		if err := os.WriteFile(filepath.Join(*out, n), src, 0o644); err != nil {
			fatal(err)
		}
	}
	if *layoutC != "" {
		if err := os.WriteFile(*layoutC, []byte(g.layoutProgram()), 0o644); err != nil {
			fatal(err)
		}
	}
	if *layoutExp != "" {
		if err := os.WriteFile(*layoutExp, []byte(g.layoutExpect()), 0o644); err != nil {
			fatal(err)
		}
	}
	for _, w := range g.warnings {
		fmt.Fprintln(os.Stderr, "warn:", w)
	}
}
