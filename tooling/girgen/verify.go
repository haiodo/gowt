package main

import (
	"fmt"
	"sort"
	"strings"
)

// layoutProgram is a C program printing "CType size off..." per struct, to diff against the
// computed layouts (tooling/girgen/verify.sh).
func (g *gen) layoutProgram() string {
	var b strings.Builder
	b.WriteString("#include <stdio.h>\n#include <stddef.h>\n#include <gtk/gtk.h>\n#include <gdk/gdkx.h>\n#include <pango/pangocairo.h>\n#include <cairo-xlib.h>\n#include <X11/Xlib.h>\nint main(void) {\n")
	var cts []string
	for ct := range g.layouts {
		cts = append(cts, ct)
	}
	sort.Strings(cts)
	for _, ct := range cts {
		l := g.layouts[ct]
		fmt.Fprintf(&b, "\tprintf(\"%s %%zu\", sizeof(%s));\n", ct, ct)
		for _, f := range l.Fields {
			if f.Synthetic || (l.Union && f.Off != 0) {
				continue
			}
			fmt.Fprintf(&b, "\tprintf(\" %s=%%zu\", offsetof(%s, %s));\n", f.Name, ct, f.CPath)
		}
		b.WriteString("\tprintf(\"\\n\");\n")
	}
	b.WriteString("\treturn 0;\n}\n")
	return b.String()
}

// layoutExpect prints the same table from the computed layouts.
func (g *gen) layoutExpect() string {
	var b strings.Builder
	var cts []string
	for ct := range g.layouts {
		cts = append(cts, ct)
	}
	sort.Strings(cts)
	for _, ct := range cts {
		l := g.layouts[ct]
		fmt.Fprintf(&b, "%s %d", ct, l.Size)
		for _, f := range l.Fields {
			if f.Synthetic || (l.Union && f.Off != 0) {
				continue
			}
			fmt.Fprintf(&b, " %s=%d", f.Name, f.Off)
		}
		b.WriteString("\n")
	}
	return b.String()
}

// layoutTest is a Go test asserting every generated struct has the computed size and offsets.
func (g *gen) layoutTest(structNames map[string]bool) string {
	var b strings.Builder
	b.WriteString("// Code generated by girgen from GIR files. DO NOT EDIT.\n//go:build linux\n\npackage gtk\n\nimport (\n\t\"testing\"\n\t\"unsafe\"\n)\n\n")
	b.WriteString("func TestGeneratedLayouts(t *testing.T) {\n\tcheck := func(name string, got, want uintptr) {\n\t\tif got != want {\n\t\t\tt.Errorf(\"%s: %d, want %d\", name, got, want)\n\t\t}\n\t}\n")
	var cts []string
	for ct := range g.layouts {
		cts = append(cts, ct)
	}
	sort.Strings(cts)
	for _, ct := range cts {
		l := g.layouts[ct]
		n := exportName(ct)
		if !structNames[n] || g.shapes.Wide[ct] {
			continue
		}
		if len(l.Bits) == 0 && len(g.shapes.Extra[ct]) == 0 { // extra Go-only fields make the struct bigger than C's
			fmt.Fprintf(&b, "\tcheck(%q, unsafe.Sizeof(%s{}), %d)\n", n, n, l.Size)
		}
		for _, f := range l.Fields {
			if f.Synthetic || (l.Union && f.Off != 0) || strings.HasPrefix(f.Name, "_") || (l.Union && f.Name != l.Fields[0].Name) {
				continue
			}
			fmt.Fprintf(&b, "\tcheck(%q, unsafe.Offsetof(%s{}.%s), %d)\n", n+"."+f.Name, n, exportName(f.Name), f.Off)
		}
	}
	b.WriteString("}\n")
	return b.String()
}
