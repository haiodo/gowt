package dev.gowt.j2go.emit;

import dev.gowt.j2go.Names;
import dev.gowt.j2go.TypeModel;
import org.eclipse.jdt.core.dom.*;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Set;
import java.util.TreeSet;

/** `J2GO_DUMP_PUBLIC`: the Go names of the public Java API of package swt, merged over runs and platforms (apidump filters by it). */
public final class PublicApi {

	private PublicApi() {}

	public static void dump(Emitter emitter, Path file) throws IOException {
		Set<String> all = new TreeSet<>();
		if (Files.exists(file)) all.addAll(Files.readAllLines(file));
		all.removeIf(l -> l.startsWith("#"));
		for (TypeModel.ClassInfo ci : emitter.model.all()) {
			if (!ci.goPackage.equals("swt") || !Modifier.isPublic(ci.binding.getModifiers()) || ci.javaPackage.contains(".internal")) continue;
			all.add("type " + ci.goTypeName);
			if (ci.likeInterfaceName != null) {
				all.add("type " + ci.likeInterfaceName);
				all.add("method " + ci.goTypeName + "." + ci.asMethodName);
				all.add("method " + ci.likeInterfaceName + "." + ci.asMethodName);
			}
			// The public methods of the class and of every ancestor are the class's own API (Go promotes them).
			for (TypeModel.ClassInfo c = ci; c != null; c = c.superclass) for (IMethodBinding mb : c.binding.getDeclaredMethods()) {
				int mods = mb.getModifiers();
				if (!Modifier.isPublic(mods) && !Modifier.isProtected(mods)) continue;
				boolean isStatic = Modifier.isStatic(mods);
				if (c != ci && (mb.isConstructor() || isStatic)) continue;
				if (mb.isConstructor()) {
					all.add("func " + emitter.names.goMemberName(mb, "New" + ci.goFuncPrefix));
				} else if (isStatic) {
					all.add("func " + EmitUtil.staticMethodGoName(emitter, ci, emitter.names.goMemberName(mb, Names.javaMethodBaseGoName(mb.getName()))));
				} else {
					all.add("method " + ci.goTypeName + "." + emitter.names.goMemberName(mb, Names.javaMethodBaseGoName(mb.getName())));
					if (ci.likeInterfaceName != null) all.add("method " + ci.likeInterfaceName + "." + emitter.names.goMemberName(mb, Names.javaMethodBaseGoName(mb.getName())));
				}
			}
			for (IVariableBinding vb : ci.binding.getDeclaredFields()) {
				if (Modifier.isPublic(vb.getModifiers()) && Modifier.isStatic(vb.getModifiers())) all.add("func " + EmitUtil.staticFieldGoName(emitter, ci, vb.getName()));
			}
		}
		Files.writeString(file, "# Generated by j2go (J2GO_DUMP_PUBLIC): Go names of the public Java API of swt, all platforms.\n" + String.join("\n", all) + "\n");
	}
}
