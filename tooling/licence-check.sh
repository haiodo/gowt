#!/usr/bin/env bash
# Every .go file translated from Java by j2go must keep the original licence header (EPL-2.0 3.2/3.3):
# an SPDX-License-Identifier: EPL-2.0 line (the two gtk files Red Hat and Syntevo published under the LGPL carry
# the LGPL text instead) and a Copyright line in the comments above the package clause.
set -euo pipefail
cd "$(dirname "$0")/.."

bad=$(git ls-files '*.go' ':!tooling/j2go/testdata' | xargs awk '
	function report() { if (gen && !(spdx && copy)) print f }
	FNR == 1 { if (f != "") report(); f = FILENAME; spdx = 0; copy = 0; gen = ($0 ~ /^\/\/ Code generated by j2go from /); done = 0 }
	done { next }
	/^package / { done = 1; next }
	/SPDX-License-Identifier: EPL-2\.0|GNU Lesser General Public License/ { spdx = 1 }
	/Copyright/ { copy = 1 }
	END { report() }
' | sort)
if [ -n "$bad" ]; then
	echo "licence-check: translated files without an EPL-2.0 SPDX line and a Copyright line in the header:" >&2
	echo "$bad" >&2
	exit 1
fi
echo "licence-check: ok"
