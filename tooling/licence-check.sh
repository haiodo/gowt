#!/usr/bin/env bash
# Every .go file translated from Java by j2go must keep the original licence header (EPL-2.0 3.2/3.3):
# an SPDX-License-Identifier: EPL-2.0 line and a Copyright line in the comments above the package clause.
# The repository is EPL-2.0 only: no tracked file may carry the LGPL text.
set -euo pipefail
cd "$(dirname "$0")/.."

bad=$(git ls-files '*.go' ':!tooling/j2go/testdata' | xargs awk '
	function report() { if (gen && !(spdx && copy)) print f }
	FNR == 1 { if (f != "") report(); f = FILENAME; spdx = 0; copy = 0; gen = ($0 ~ /^\/\/ Code generated by j2go from /); done = 0 }
	done { next }
	/^package / { done = 1; next }
	/SPDX-License-Identifier: EPL-2\.0/ { spdx = 1 }
	/Copyright/ { copy = 1 }
	END { report() }
' | sort)
if [ -n "$bad" ]; then
	echo "licence-check: translated files without an EPL-2.0 SPDX line and a Copyright line in the header:" >&2
	echo "$bad" >&2
	exit 1
fi
lgpl=$(git grep -l -I "GNU Lesser General Public License" -- . ':!tooling/licence-check.sh' || true)
if [ -n "$lgpl" ]; then
	echo "licence-check: LGPL text found (the repository is EPL-2.0 only):" >&2
	echo "$lgpl" >&2
	exit 1
fi
echo "licence-check: ok"
