#!/usr/bin/env bash
# Runs j2go over the swt, PI bindings (internal/<platform>) and examples/controlexample file lists.
# --out is the repo root: each file lands under swt/, internal/<platform>/ or examples/<name>/ per its
# own Java package (see GoTypes.goPackageDir). PLATFORM=cocoa|win32|gtk picks the platform sources;
# files translated from them get a _<goos>.go suffix, files from */common stay unsuffixed.
set -euo pipefail
cd "$(dirname "$0")/.."

SWT_REPO="${SWT_REPO:-/Users/haiodo/Develop/repos/eclipse.platform.swt}"
PLATFORM="${PLATFORM:-cocoa}"
case "$PLATFORM" in
	cocoa) GOOS_NAME=darwin ;;
	win32) GOOS_NAME=windows ;;
	gtk) GOOS_NAME=linux ;;
	*) echo "port.sh: unknown PLATFORM=$PLATFORM (cocoa, win32, gtk)" >&2; exit 2 ;;
esac
PI_DIR="internal/$PLATFORM"
PI_SRC="$SWT_REPO/bundles/org.eclipse.swt/Eclipse SWT PI/$PLATFORM/org/eclipse/swt/internal/$PLATFORM"
J2GO=(java -jar tooling/j2go/target/j2go.jar --swt "$SWT_REPO" --out . --platform "$PLATFORM")
EVENTS_DIR="$SWT_REPO/bundles/org.eclipse.swt/Eclipse SWT/common/org/eclipse/swt/events"

mvn -q -f tooling/j2go/pom.xml package

# gtk: Java declarations of internal/gtk's API for j2go (type information; no PI sources), made from the call
# sites in swt/ before the cleanup below removes them.
if [ "$PLATFORM" = gtk ]; then
	rm -rf tooling/j2go/gtkstubs-gen
	go build -o bin/girgen ./tooling/girgen
	GOOS=linux ./bin/girgen -jstubs tooling/j2go/gtkstubs-gen
fi

# Drops the generated files of the shared set (cocoa only: it is the reference platform that owns the shared
# files, see README "Round 20") and of this platform (a renamed or removed source then leaves nothing stale);
# another platform's _<goos>.go files stay.
for f in swt/*.go swt/swtreflect/*.go "$PI_DIR"/*.go examples/*/*.go tests/swttests/*.go jface/*.go tests/jfacetests/*.go browser/*.go; do
	[ -e "$f" ] || continue
	case "$f" in
		"$PI_DIR"/*) ;;
		*_darwin.go | *_windows.go | *_linux.go) [ "${f%_"$GOOS_NAME".go}" != "$f" ] || continue ;;
		*) [ "$PLATFORM" = cocoa ] || continue ;;
	esac
	if head -1 "$f" | grep -q '^// Code generated by j2go'; then rm "$f"; fi
done

# Round 3: SWT.java/SWTException/SWTError, Listener/Event/EventTable/TypedListener and the whole
# events/ package now join stage-1's graphics types in one invocation - TypeModel is
# per-invocation (see README "Round 2"), and SWT.java references Point/Rectangle-adjacent
# constants while TypedListener.java references every events/* type directly.
mapfile -t EVENTS_FILES < <(find "$EVENTS_DIR" -maxdepth 1 -name '*.java' -exec basename {} \; | sort | sed 's#^#org/eclipse/swt/events/#')

# Checkpoint b: every Eclipse SWT PI/cocoa class in one j2go run (all of them share bindings -
# TypeModel is per-invocation, see README "Round 2"), plus C.java (PI/common, OS.java's own
# base for memmove/malloc/PTR_sizeof). Selector.java is deliberately excluded from the file
# list - not parsed as a translation target at all, only resolved via sourcepath for the
# structural sel_x.value -> OSSel_registerName(...) rewrite (see README "Selector enum elision").
# -printf is a GNU find extension, not on macOS's BSD find - list + basename instead.
if [ "$PLATFORM" = gtk ]; then
	# gtk: type information for the PI classes comes from Java declarations generated out of internal/gtk's own
	# Go declarations (tooling/girgen -jstubs) plus hand stubs for the few PI/common classes the widgets use.
	PI_FILES=(org/eclipse/swt/internal/Converter.java) # EPL, under Eclipse SWT/gtk; calls the stubs
	for d in tooling/j2go/gtkstubs-gen tooling/j2go/gtkstubs; do
		while IFS= read -r f; do PI_FILES+=("${f#$d/}"); done < <(find "$d" -name '*.java' | sort)
	done
elif [ "$PLATFORM" = win32 ]; then
	# win32's PI is four packages (win32, win32/version, gdip, ole/win32), all Go package internal/win32.
	PI_ROOT="$SWT_REPO/bundles/org.eclipse.swt/Eclipse SWT PI/win32"
	mapfile -t PI_FILES < <(cd "$PI_ROOT" && find org/eclipse/swt/internal -name '*.java' ! -name Platform.java | sort)
	PI_FILES+=(org/eclipse/swt/internal/ole/win32/COMObject.java) # Eclipse SWT OLE Win32: the vtable base of Accessible
else
	mapfile -t PI_FILES < <(find "$PI_SRC" -maxdepth 1 -name '*.java' ! -name 'Selector.java' -exec basename {} \; | sort | sed "s#^#org/eclipse/swt/internal/$PLATFORM/#")
fi

